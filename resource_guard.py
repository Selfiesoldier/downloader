import logging
import os
import shutil
import tempfile
import time
from pathlib import Path
from typing import Tuple, List

logger = logging.getLogger("resource_guard")

# Minimum free disk headroom required (500 MB)
DEFAULT_MIN_HEADROOM_MB = 500

# Critical protected filenames and directory patterns that must never be deleted
PROTECTED_PATTERNS = {
    "cookies",
    ".env",
    ".git",
    ".session",
    ".session-journal",
    ".venv",
    "__pycache__",
}
PROTECTED_EXTENSIONS = {
    ".session",
    ".session-journal",
    ".env",
    ".py",
    ".md",
    ".json",
    ".txt",
    ".git",
}
STALE_FILE_EXTENSIONS = {
    ".part",
    ".ytdl",
    ".temp",
}


class DiskHeadroomGuard:
    """
    Guards storage on mobile environments (e.g. Android Termux) by enforcing
    a minimum 500MB free disk headroom plus 1.5x expected download size.
    """

    @staticmethod
    def check_headroom(
        target_dir: str = ".",
        estimated_bytes: int = 0,
        min_headroom_mb: int = DEFAULT_MIN_HEADROOM_MB,
    ) -> Tuple[bool, str]:
        """
        Inspects free storage using shutil.disk_usage.
        Requires free space >= max(min_headroom_mb, 1.5 * estimated_bytes).
        Returns (True, "") or (False, advisory_message).
        """
        try:
            target_path = Path(target_dir).resolve()
            # If target dir does not exist yet, check its existing parent
            while not target_path.exists() and target_path.parent != target_path:
                target_path = target_path.parent

            usage = shutil.disk_usage(str(target_path))
            free_bytes = usage.free
            min_headroom_bytes = min_headroom_mb * 1024 * 1024
            required_bytes = max(min_headroom_bytes, int(1.5 * estimated_bytes))

            if free_bytes < required_bytes:
                free_mb = free_bytes / (1024 * 1024)
                req_mb = required_bytes / (1024 * 1024)
                advisory = (
                    f"⚠️ Insufficient disk space: Only {free_mb:.1f} MB free, but {req_mb:.1f} MB required "
                    f"(minimum {min_headroom_mb} MB safety headroom). Please free up device storage before downloading."
                )
                logger.warning("Disk headroom check failed: %s", advisory)
                return False, advisory

            return True, ""
        except Exception as err:
            logger.error("Error inspecting disk headroom for %s: %s", target_dir, err)
            # Default to allowing with a warning if disk_usage is unsupported by OS
            return True, ""


def check_disk_headroom(
    target_dir: str = ".",
    estimated_bytes: int = 0,
    min_headroom_mb: int = DEFAULT_MIN_HEADROOM_MB,
) -> Tuple[bool, str]:
    """Module-level alias for DiskHeadroomGuard.check_headroom."""
    return DiskHeadroomGuard.check_headroom(
        target_dir=target_dir,
        estimated_bytes=estimated_bytes,
        min_headroom_mb=min_headroom_mb,
    )


class OrphanCleaner:
    """
    Cleans up orphaned temporary download directories (dl_*) and stale .part/.ytdl/.temp files
    generated by aborted, cancelled, or completed downloads.
    """

    @classmethod
    def is_protected(cls, path: Path) -> bool:
        """Determines if a path is protected from automated cleanup."""
        path_str = str(path).lower()
        name = path.name.lower()

        # Check suffix
        if path.suffix.lower() in PROTECTED_EXTENSIONS:
            return True

        # Check filename / path components
        for pattern in PROTECTED_PATTERNS:
            if pattern in name:
                return True
            for part in path.parts:
                if part.lower() == pattern or pattern in part.lower():
                    return True

        return False

    @classmethod
    def clean(
        cls,
        base_dir: str = ".",
        max_age_seconds: int = 3600,
        scan_system_temp: bool = True,
    ) -> List[str]:
        """
        Scans base_dir and optionally system temp for directories starting with 'dl_'
        and files ending in .part, .ytdl, or .temp older than max_age_seconds.
        Safely removes stale entries while protecting sessions, cookies, and code.
        """
        purged: List[str] = []
        now = time.time()

        scan_dirs = [Path(base_dir).resolve()]
        if scan_system_temp:
            sys_tmp = Path(tempfile.gettempdir()).resolve()
            if sys_tmp not in scan_dirs:
                scan_dirs.append(sys_tmp)

        for directory in scan_dirs:
            if not directory.exists() or not directory.is_dir():
                continue

            try:
                # 1. Sweep dl_* directories
                for item in list(directory.iterdir()):
                    if item.is_dir() and item.name.startswith("dl_"):
                        if cls.is_protected(item):
                            continue
                        try:
                            mtime = item.stat().st_mtime
                            if max_age_seconds <= 0 or (now - mtime) > max_age_seconds:
                                shutil.rmtree(str(item), ignore_errors=True)
                                purged.append(str(item))
                                logger.info("Purged orphaned temp directory: %s", item)
                        except Exception as e:
                            logger.debug("Failed to inspect/remove temp directory %s: %e", item, e)

                # 2. Sweep stray stale .part, .ytdl, and .temp files
                for root_str, dirs, files in os.walk(str(directory)):
                    root_path = Path(root_str)
                    if cls.is_protected(root_path):
                        # Skip walking protected directories entirely
                        dirs.clear()
                        continue

                    # Don't walk deep into node_modules, git, or venv
                    dirs[:] = [d for d in dirs if not cls.is_protected(root_path / d)]

                    for fname in files:
                        fpath = root_path / fname
                        if cls.is_protected(fpath):
                            continue

                        if fpath.suffix.lower() in STALE_FILE_EXTENSIONS:
                            try:
                                mtime = fpath.stat().st_mtime
                                if max_age_seconds <= 0 or (now - mtime) > max_age_seconds:
                                    fpath.unlink(missing_ok=True)
                                    purged.append(str(fpath))
                                    logger.info("Purged stale download artifact: %s", fpath)
                            except Exception as e:
                                logger.debug("Failed to remove stale file %s: %s", fpath, e)

            except Exception as e:
                logger.debug("Error during orphan sweep in %s: %s", directory, e)

        return purged


def clean_orphaned_temp_dirs(
    base_dir: str = ".",
    max_age_seconds: int = 3600,
    scan_system_temp: bool = True,
) -> List[str]:
    """Module-level alias for OrphanCleaner.clean."""
    return OrphanCleaner.clean(
        base_dir=base_dir,
        max_age_seconds=max_age_seconds,
        scan_system_temp=scan_system_temp,
    )


class SmartQualityBadges:
    """
    Generates bandwidth-aware quality badges indicating speed and size.
    """

    @staticmethod
    def format_badge(
        height: int = 0,
        file_size_bytes: int = 0,
        is_audio: bool = False,
    ) -> str:
        """
        Produces clean, intuitive labels:
          720p: "⚡ Fast 720p (~30MB)"
          1080p: "🎬 Full 1080p (~150MB)"
          480p / 360p: "💾 Data Saver 480p (~15MB)"
          Audio: "🎵 Audio (MP3) (~8MB)"
        """
        def _calc_size_str(default_str: str) -> str:
            if file_size_bytes > 0:
                mb = file_size_bytes / (1024 * 1024)
                return f"~{int(round(mb))}MB" if mb >= 1 else f"~{round(mb, 1)}MB"
            return default_str

        if is_audio:
            size_str = _calc_size_str("~8MB")
            return f"🎵 Audio (MP3) ({size_str})"

        if height >= 1080:
            size_str = _calc_size_str("~150MB")
            return f"🎬 Full {height}p ({size_str})"

        if height >= 720:
            size_str = _calc_size_str("~30MB")
            return f"⚡ Fast {height}p ({size_str})"

        if height in (360, 480) or (0 < height < 720):
            size_str = _calc_size_str("~15MB")
            label_height = height if height > 0 else 480
            return f"💾 Data Saver {label_height}p ({size_str})"

        # Generic default
        size_str = _calc_size_str("~50MB")
        return f"🎬 Best Video ({size_str})"


def format_quality_badge(
    height: int = 0,
    file_size_bytes: int = 0,
    is_audio: bool = False,
) -> str:
    """Module-level alias for SmartQualityBadges.format_badge."""
    return SmartQualityBadges.format_badge(
        height=height,
        file_size_bytes=file_size_bytes,
        is_audio=is_audio,
    )
